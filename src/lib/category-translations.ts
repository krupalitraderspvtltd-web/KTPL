export function getLocalizedCategoryName(
  name: string,
  locale: string
): string {
  const key = name.trim().toLowerCase();
  const normalizedLocale =
    locale === "zh-CN" || locale === "zh-TW"
      ? locale
      : locale.split("-")[0];

  return (
    CATEGORY_TRANSLATIONS[key]?.[locale] ||
    CATEGORY_TRANSLATIONS[key]?.[normalizedLocale] ||
    name
  );
}
